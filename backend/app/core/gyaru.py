def to_hyper_gal_v3(text: str) -> str:
    """
    LLMが生成した全角の日本語を、極限ギャル文字（Lv3）に変換するコンパイラ関数。
    """
    # 1. 保護処理（URL、XMLタグ、インラインコード、メンション、英数字の単語を除外）
    shield_pattern = re.compile(r'(```[\s\S]*?```|\[[^\]]*\]\([^\)]*\)|https?://[^\s]+|<[^>]+>|`[^`]+`|@[\w\-]+|[a-zA-Z0-9_]+)')
    parts = shield_pattern.split(text)
    
    for i in range(len(parts)):
        if i % 2 == 1:
            continue # シールド部分はそのまま
            
        part = parts[i]
        
        # 2. 単語・漢字分解マッピング（前方一致置換）
        for k, v in WORD_MAP.items():
            part = part.replace(k, v)
            
        # 3. 1文字ごとのギャル文字変換
        compiled_chars = []
        for char in part:
            compiled_chars.append(CHAR_MAP.get(char, char))
        
        parts[i] = "".join(compiled_chars)
        
    return "".join(parts)
